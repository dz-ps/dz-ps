#!/usr/bin/env node
// Copies packages/shared/src (non-test files) into supabase/functions/_shared/riftbuild-shared so Edge
// Functions run the exact same rule/validation code as the app (DECISIONS.md D2).
// `--check` exits 1 when the committed copy is out of date.
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const srcDir = join(root, 'packages/shared/src');
const outDir = join(root, 'supabase/functions/_shared/riftbuild-shared');
const check = process.argv.includes('--check');
const HEADER =
  '// GENERATED by scripts/sync-shared-to-deno.mjs from packages/shared/src. DO NOT EDIT.\n';
const ALLOWED_BARE = new Set(['zod']);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return walk(full);
    return name.endsWith('.ts') && !name.endsWith('.test.ts') ? [full] : [];
  });
}

const problems = [];
const expected = new Map();
for (const file of walk(srcDir)) {
  const rel = relative(srcDir, file);
  const code = readFileSync(file, 'utf8');
  for (const match of code.matchAll(/(?:import|export)[^'"]*?from\s+['"]([^'"]+)['"]/g)) {
    const spec = match[1];
    if (spec.startsWith('.')) {
      if (!spec.endsWith('.ts')) problems.push(`${rel}: relative import "${spec}" must end in .ts`);
    } else if (!ALLOWED_BARE.has(spec)) {
      problems.push(
        `${rel}: bare import "${spec}" is not allowed in shared (only ${[...ALLOWED_BARE]})`,
      );
    }
  }
  expected.set(rel, HEADER + code);
}

if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

const zodVersion = JSON.parse(readFileSync(join(root, 'packages/shared/package.json'), 'utf8'))
  .dependencies.zod;
const denoJsonPath = join(root, 'supabase/functions/deno.json');
const denoJson = existsSync(denoJsonPath) ? JSON.parse(readFileSync(denoJsonPath, 'utf8')) : {};
denoJson.imports = { ...(denoJson.imports ?? {}), zod: `npm:zod@${zodVersion}` };
const denoJsonText = JSON.stringify(denoJson, null, 2) + '\n';

if (check) {
  const stale = [];
  const existing = existsSync(outDir) ? walk(outDir).map((f) => relative(outDir, f)) : [];
  for (const [rel, content] of expected) {
    const target = join(outDir, rel);
    if (!existsSync(target) || readFileSync(target, 'utf8') !== content) stale.push(rel);
  }
  for (const rel of existing) if (!expected.has(rel)) stale.push(`${rel} (orphan)`);
  if (!existsSync(denoJsonPath) || readFileSync(denoJsonPath, 'utf8') !== denoJsonText)
    stale.push('deno.json');
  if (stale.length) {
    console.error(`Deno copy of shared is stale; run \`pnpm sync:deno\`:\n  ${stale.join('\n  ')}`);
    process.exit(1);
  }
  console.log('Deno copy of shared is up to date.');
} else {
  rmSync(outDir, { recursive: true, force: true });
  for (const [rel, content] of expected) {
    const target = join(outDir, rel);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
  mkdirSync(dirname(denoJsonPath), { recursive: true });
  writeFileSync(denoJsonPath, denoJsonText);
  console.log(`Synced ${expected.size} files to ${relative(root, outDir)}`);
}
